<#
  Refreshes the wiki from the two Google Docs:
    - the story doc ("Luma Guardian About")  -> wiki/data/story.md       (Lore pages)
    - the characters doc ("LG Characters")  -> wiki/data/characters/ and wiki/data/people.json (profiles, teams, civilians)
  The cleaned copy of the characters doc is only kept while building; it is not saved in the repo.

  Run from the repo folder with Markdown copies of the docs (either or both):
      powershell -ExecutionPolicy Bypass -File wiki\tools\update-story.ps1 -Source "Luma Guardian About.md" -CharactersSource "LG Characters.md"
  Each doc tab must start with a plain "# Tab name" line ending in two spaces (how Google's Markdown export writes tabs).
  Google's own File > Download > Markdown only saves the open tab, so the easiest refresh is to ask Claude
  (with Google Drive connected) to re-import the docs.

  What it does:
  - turns each doc tab heading into a <!-- tab: Name --> marker
  - drops the tabs listed in storyExcludeTabs (wiki/data/wiki.json), and any tab containing "[Hidden Tab"
  - deletes every "Label: value" line whose label is in hideFields (wiki.json) or hiddenFields (branches.json),
    so body measurements and other private fields never reach the public repo
#>
param([string]$Source, [string]$CharactersSource)
$ErrorActionPreference = 'Stop'
$wiki = Split-Path $PSScriptRoot -Parent
$utf8 = New-Object System.Text.UTF8Encoding($false)

$cfg = [IO.File]::ReadAllText((Join-Path $wiki 'data\wiki.json'), $utf8) | ConvertFrom-Json
$branches = [IO.File]::ReadAllText((Join-Path $wiki 'data\branches.json'), $utf8) | ConvertFrom-Json

if (-not $Source -and -not $CharactersSource) {
    # Google's public export link only returns the first tab, so full Markdown copies have to be passed in.
    throw 'Pass -Source <story doc .md> and/or -CharactersSource <characters doc .md>: Markdown copies of the whole docs, each tab starting with a "# Tab name" line.'
}

$hide = @($cfg.hideFields) + @($branches.hiddenFields) | Where-Object { $_ } | Sort-Object -Unique
$hideRe = '^\s*(?:[-*]\s+)?(?:' + (($hide | ForEach-Object { [regex]::Escape($_) }) -join '|') + ')\b[^:\n]{0,40}:'
$exclude = @($cfg.storyExcludeTabs) | Where-Object { $_ } | ForEach-Object { $_.Trim().ToLower() }
# A doc tab exports as a plain "# Tab name" line ending in two spaces; section headings are bold (# **Name**).
$tabRe = '^# ([^*\\#\s].*?\S) {2}$'

function Convert-Doc([string]$src, [string]$dest, [string]$single) {
    $text = [IO.File]::ReadAllText((Resolve-Path $src), $utf8) -replace "`r`n?", "`n"
    # Embedded images export as huge base64 blobs; drop them and their placeholders.
    $text = $text -replace '(?m)^\[image\d+\]:\s*<data:[^>]*>\s*$', '' -replace '!\[[^\]]*\]\[image\d+\]', ''
    $hasTabs = [regex]::IsMatch($text, $tabRe, 'Multiline')

    # Split into tabs first, so a whole tab can be dropped.
    $tabs = New-Object System.Collections.Generic.List[object]
    $cur = @{ name = $single; lines = (New-Object System.Collections.Generic.List[string]) }
    if (-not $hasTabs) { $tabs.Add($cur) }
    foreach ($line in $text -split "`n") {
        $m = [regex]::Match($line, $tabRe)
        if ($hasTabs -and $m.Success) {
            # Struck-through tab names ("Pairings~~") are cleaned up.
            $cur = @{ name = ($m.Groups[1].Value -replace '~~', '').Trim(); lines = (New-Object System.Collections.Generic.List[string]) }
            $tabs.Add($cur); continue
        }
        $cur.lines.Add($line)
    }

    $out = New-Object System.Collections.Generic.List[string]
    $out.Add("<!-- Generated by wiki/tools/update-story.ps1 on $(Get-Date -Format 'yyyy-MM-dd'). Edit the Google Doc and re-run instead of editing this file. -->")
    $kept = 0; $removed = 0; $dropped = @()
    foreach ($t in $tabs) {
        $body = $t.lines -join "`n"
        if (($exclude -contains $t.name.ToLower()) -or $body -match '\[Hidden Tab') { $dropped += $t.name; continue }
        $out.Add(''); $out.Add("<!-- tab: $($t.name) -->"); $kept++
        foreach ($line in $t.lines) {
            $plain = $line -replace '[*_]', ''
            if ($hide.Count -and $plain -match $hideRe) { $removed++; continue }
            $out.Add($line.TrimEnd())
        }
    }
    # Collapse runs of blank lines.
    $md = ($out -join "`n") -replace "\n{3,}", "`n`n"
    [IO.File]::WriteAllText($dest, $md.Trim() + "`n", $utf8)
    Write-Host "Cleaned $(Split-Path $src -Leaf): $kept tabs, $removed hidden-field lines removed$(if ($dropped.Count) { "; left out: $($dropped -join ', ')" })."
}

if ($Source) {
    $dest = Join-Path $wiki 'data\story.md'
    Convert-Doc $Source $dest 'Story'
    Write-Host "Wrote $dest"
}
if ($CharactersSource) {
    # The characters doc is only used to build the character files and people.json; its cleaned copy is not kept.
    $tmp = Join-Path $env:TEMP 'luma-characters-cleaned.md'
    Convert-Doc $CharactersSource $tmp 'Characters'
    try { & (Join-Path $PSScriptRoot 'build-characters.ps1') -Source $tmp }
    finally { Remove-Item $tmp -ErrorAction SilentlyContinue }
}
