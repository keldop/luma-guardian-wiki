<#
  Refreshes wiki/data/story.md from the Luma Guardian Google Doc.

  Run from the repo folder with a Markdown copy of the whole doc:
      powershell -ExecutionPolicy Bypass -File wiki\tools\update-story.ps1 -Source "$HOME\Downloads\Luma Guardian About.md"
  Each doc tab must start with a plain "# Tab name" line ending in two spaces (how Google's Markdown export writes tabs).
  Google's own File > Download > Markdown only saves the open tab, so the easiest refresh is to ask Claude
  (with Google Drive connected) to re-import the doc.

  What it does:
  - turns each doc tab heading into a <!-- tab: Name --> marker (one wiki Lore page per tab)
  - drops the tabs listed in storyExcludeTabs (wiki/data/wiki.json)
  - deletes every "Label: value" line whose label is in hideFields (wiki.json) or hiddenFields (branches.json),
    so civilian names, birthdays and body measurements never reach the public repo
#>
param([string]$Source)
$ErrorActionPreference = 'Stop'
$wiki = Split-Path $PSScriptRoot -Parent
$utf8 = New-Object System.Text.UTF8Encoding($false)

$cfg = [IO.File]::ReadAllText((Join-Path $wiki 'data\wiki.json'), $utf8) | ConvertFrom-Json
$branches = [IO.File]::ReadAllText((Join-Path $wiki 'data\branches.json'), $utf8) | ConvertFrom-Json

if (-not $Source) {
    # Google's public export link only returns the first tab, so a full Markdown copy has to be passed in.
    throw 'Pass -Source <file.md>: a Markdown copy of the whole doc, with each tab starting with a "# Tab name" line.'
}
$text = [IO.File]::ReadAllText((Resolve-Path $Source), $utf8) -replace "`r`n?", "`n"
# Embedded images export as huge base64 blobs; drop them and their placeholders.
$text = $text -replace '(?m)^\[image\d+\]:\s*<data:[^>]*>\s*$', '' -replace '!\[[^\]]*\]\[image\d+\]', ''

$hide = @($cfg.hideFields) + @($branches.hiddenFields) | Where-Object { $_ } | Sort-Object -Unique
$hideRe = '^\s*(?:[-*]\s+)?(?:' + (($hide | ForEach-Object { [regex]::Escape($_) }) -join '|') + ')\b[^:\n]{0,40}:'
$exclude = @($cfg.storyExcludeTabs) | Where-Object { $_ } | ForEach-Object { $_.Trim().ToLower() }

# A doc tab exports as a plain "# Tab name" line ending in two spaces; section headings are bold (# **Name**).
$tabRe = '^# ([^*\\#\s].*?\S) {2}$'
$hasTabs = [regex]::IsMatch($text, $tabRe, 'Multiline')

$out = New-Object System.Collections.Generic.List[string]
$out.Add("<!-- Generated by wiki/tools/update-story.ps1 on $(Get-Date -Format 'yyyy-MM-dd'). Edit the Google Doc and re-run instead of editing this file. -->")
if (-not $hasTabs) { $out.Add('<!-- tab: Story -->') }
$skip = $false; $tabs = 0; $removed = 0
foreach ($line in $text -split "`n") {
    $m = [regex]::Match($line, $tabRe)
    if ($hasTabs -and $m.Success) {
        $name = $m.Groups[1].Value.Trim()
        $skip = $exclude -contains $name.ToLower()
        if (-not $skip) { $out.Add(''); $out.Add("<!-- tab: $name -->"); $tabs++ }
        continue
    }
    if ($skip) { continue }
    $plain = $line -replace '[*_]', ''
    if ($hide.Count -and $plain -match $hideRe) { $removed++; continue }
    $out.Add($line.TrimEnd())
}

# Collapse runs of blank lines.
$md = ($out -join "`n") -replace "\n{3,}", "`n`n"
$dest = Join-Path $wiki 'data\story.md'
[IO.File]::WriteAllText($dest, $md.Trim() + "`n", $utf8)
Write-Host "Wrote $dest : $([Math]::Max($tabs,1)) tabs, $removed hidden-field lines removed."

# Character profiles (data/characters.json) are rebuilt from the new story.
& (Join-Path $PSScriptRoot 'build-characters.ps1')
